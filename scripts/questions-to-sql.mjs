/**
 * Prints the SQL that seeds one lesson's questions into public.inline_questions.
 * It never connects to a database: the output is meant to be SHOWN to the owner and, once approved,
 * run through the Supabase MCP (live project zgofeajewktwmswckgup only).
 *
 *   node scripts/questions-to-sql.mjs content/courses/<slug>/<lesson>.mdx   > seed.sql
 *
 * - Runs scripts/validate-questions.mjs first and refuses on any ERROR.
 * - Reads <lesson>.questions.json; strips the authoring-only notes (`concept`, `distractors`).
 * - One transaction. The lesson is resolved by (course slug, order_index) AND checked by title, type and
 *   published flag; refuses if the lesson already has questions (re-seeding would wipe students' attempts —
 *   attempts cascade — so replacing is a deliberate manual decision, not a flag).
 * - Post-checks: the row count, and that every stored content equals the file's content (jsonb equality).
 * - Any failed guard raises and rolls everything back.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { spawnSync } from "child_process";
import matter from "gray-matter";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = process.argv[2];
if (!arg) {
  console.error("usage: node scripts/questions-to-sql.mjs content/courses/<slug>/<lesson>.mdx");
  process.exit(2);
}
const mdxPath = path.resolve(process.cwd(), arg.replace(/\.questions\.json$/, ".mdx"));
const qPath = mdxPath.replace(/\.mdx$/, ".questions.json");
const rel = path.relative(ROOT, mdxPath).replace(/\\/g, "/");
const m = rel.match(/^content\/courses\/([^/]+)\//);
if (!m || !fs.existsSync(mdxPath) || !fs.existsSync(qPath)) {
  console.error(`need an existing content/courses/<slug>/<lesson>.mdx and its .questions.json (${rel})`);
  process.exit(2);
}

// 1) The validator is the gate.
const v = spawnSync(process.execPath, [path.join(ROOT, "scripts", "validate-questions.mjs"), mdxPath], { encoding: "utf-8" });
if (v.status !== 0) {
  process.stderr.write(v.stdout + v.stderr);
  console.error("\nvalidate-questions.mjs reported errors — refusing to emit SQL.");
  process.exit(1);
}

const slug = m[1];
const fm = matter(fs.readFileSync(mdxPath, "utf-8").replace(/\r\n/g, "\n")).data;
const { questions } = JSON.parse(fs.readFileSync(qPath, "utf-8"));
if (!questions?.length) {
  console.error("no questions to seed");
  process.exit(1);
}

const lit = (s) => {
  if (s.includes("$q$")) throw new Error("content contains the $q$ delimiter");
  return `$q$${s}$q$`;
};
const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = questions
  .map((q) => `    (${q.order}, ${sqlStr(q.type)}, ${lit(JSON.stringify(q.content))})`)
  .join(",\n");

const sql = `-- Seed ${questions.length} inline question(s) for ${slug} / lesson ${fm.order} — "${fm.title}"
-- Generated by scripts/questions-to-sql.mjs from ${path.basename(qPath)} (validator: pass). Live project only.
begin;

do $$
declare lid uuid; n int;
begin
  select l.id into lid
    from public.lessons l join public.courses c on c.id = l.course_id
   where c.slug = ${sqlStr(slug)} and l.order_index = ${fm.order}
     and l.title = ${sqlStr(fm.title)} and l.type = ${sqlStr(fm.type)} and l.is_published;
  if lid is null then raise exception 'lesson not found / title, type or published flag differ'; end if;
  select count(*) into n from public.inline_questions where lesson_id = lid;
  if n <> 0 then raise exception 'lesson already has % question(s) — refusing to seed (attempts would cascade)', n; end if;
end $$;

with lesson as (
  select l.id from public.lessons l join public.courses c on c.id = l.course_id
   where c.slug = ${sqlStr(slug)} and l.order_index = ${fm.order}
)
insert into public.inline_questions (lesson_id, type, order_index, content)
select lesson.id, v.type, v.ord, v.content::jsonb
  from lesson, (values
${rows}
  ) as v(ord, type, content);

do $$
declare lid uuid; n int; bad int;
begin
  select l.id into lid from public.lessons l join public.courses c on c.id = l.course_id
   where c.slug = ${sqlStr(slug)} and l.order_index = ${fm.order};
  select count(*) into n from public.inline_questions where lesson_id = lid;
  if n <> ${questions.length} then raise exception 'post-check: % rows, expected ${questions.length}', n; end if;
  select count(*) into bad from (values
${questions.map((q) => `    (${q.order}, ${lit(JSON.stringify(q.content))}::jsonb)`).join(",\n")}
  ) as e(ord, content)
  where not exists (select 1 from public.inline_questions i where i.lesson_id = lid and i.order_index = e.ord and i.content = e.content);
  if bad > 0 then raise exception 'post-check: % row(s) differ from the file', bad; end if;
end $$;

commit;
`;
process.stdout.write(sql);
